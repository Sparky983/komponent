@Serializable
data class WebrefData(val source: Sources, val elements: List<ElementDefinition>)
@Serializable
data class Sources(val elements: String, val idl: String)
@Serializable
data class ElementDefinition(
    val name: String,
    val namespace: String,
    val `interface`: String? = null,
    val href: String,
    val obsolete: Boolean = false,
    val void: Boolean = false,
    val attributes: List<AttributeDefinition> = emptyList(),
    val events: List<EventDefinition> = emptyList(),
