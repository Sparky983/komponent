private fun identifier(value: String): String = if (value in kotlinKeywords) "`$value`" else value

private fun returnType(element: ElementDefinition): String {
    val interfaceName = element.`interface` ?: return "org.w3c.dom.Element"
    val unavailableHtmlInterfaces = setOf(
        "HTMLFencedFrameElement", "HTMLGeolocationElement", "HTMLModelElement",
        "HTMLPortalElement", "HTMLSelectedContentElement",
    )
    return when (element.namespace) {
        "html" -> if (interfaceName.startsWith("HTML") && interfaceName !in unavailableHtmlInterfaces) interfaceName else "HTMLElement"
        "svg" -> if (interfaceName == "SVGSVGElement") interfaceName else "SVGElement"
        else -> "org.w3c.dom.Element"
    }
}

private fun parentNamespace(element: ElementDefinition): String = when (element.namespace) {
    "svg" -> if (element.name == "svg") "Html" else "Svg"
    "mathml" -> if (element.name == "math") "Html" else "MathMl"
    else -> "Html"
}

private fun childNamespace(element: ElementDefinition): String = when (element.namespace) {
    "svg" -> "Svg"
    "mathml" -> "MathMl"
    else -> "Html"
}

private val json = Json { ignoreUnknownKeys = true }

@OptIn(ExperimentalSerializationApi::class)
fun generate(input: File, folder: File) {
    val definitions = input.inputStream().use {
        json.decodeFromStream<WebrefData>(it)
    }
    folder.mkdirs()
    folder.resolve("tags.kt").writeText(buildFile(definitions), Charsets.UTF_8)
}

